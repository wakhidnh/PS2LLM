/* Virtual Text Buffer to manage typing & backspace cleanly */
#define MAX_TEXT_COLS 64
#define MAX_TEXT_ROWS 32
static char text_screen_buffer[MAX_TEXT_ROWS][MAX_TEXT_COLS];
static int cursor_col = 0;
static int cursor_row = 0;

void gs_text_init(void) {
    memset(text_screen_buffer, ' ', sizeof(text_screen_buffer));
    cursor_col = 0;
    cursor_row = 0;
}

void gs_text_clear(void) {
    memset(text_screen_buffer, ' ', sizeof(text_screen_buffer));
    cursor_col = 0;
    cursor_row = 0;
}

void gs_text_putc(char c) {
    if (c == '\n') {
        cursor_col = 0;
        cursor_row++;
        if (cursor_row >= MAX_TEXT_ROWS) cursor_row = 0;
        return;
    }
    if (c == '\b') { // Backspace handling
        if (cursor_col > 0) {
            cursor_col--;
            text_screen_buffer[cursor_row][cursor_col] = ' ';
        } else if (cursor_row > 0) {
            cursor_row--;
            cursor_col = MAX_TEXT_COLS - 1;
            text_screen_buffer[cursor_row][cursor_col] = ' ';
        }
        return;
    }

    if (cursor_col >= MAX_TEXT_COLS) {
        cursor_col = 0;
        cursor_row++;
        if (cursor_row >= MAX_TEXT_ROWS) cursor_row = 0;
    }

    text_screen_buffer[cursor_row][cursor_col] = c;
    cursor_col++;
}

void gs_text_print(const char *s) {
    while (*s) {
        gs_text_putc(*s);
        s++;
    }
}